#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Create the throwaway Athena sandbox and write profiles.yml plus e2e.env.
# Idempotent: a second run applies an empty Terraform plan and rewrites the files.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "${SCRIPT_DIR}/lib.sh"

usage() {
  cat <<'EOF'
usage: infra/up.sh [--dry-run] [--plan] [--region REGION]

  --dry-run   Print the AWS and Terraform calls. Run terraform validate.
              Does not contact AWS.
  --plan      terraform plan only (read-only AWS calls). Does not apply.
  --region    AWS region. Default: AWS_REGION, AWS_DEFAULT_REGION, or us-east-1.

Requires AWS_ACCESS_KEY_ID and AWS_SECRET_ACCESS_KEY (or another standard AWS
credential source) for a real apply. Credentials are not written to disk.
EOF
}

dry_run=0
do_plan=0
region=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run)
      dry_run=1
      shift
      ;;
    --plan)
      do_plan=1
      shift
      ;;
    --region)
      [[ $# -ge 2 ]] || e2e_die "--region needs a value"
      region="$2"
      shift 2
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      e2e_die "unknown argument: $1"
      ;;
  esac
done

if [[ -z "$region" ]]; then
  region="$(e2e_region)"
fi
e2e_export_region "$region"
[[ "$region" =~ ^[a-z]{2}-[a-z0-9-]+-[0-9]+$ ]] || e2e_die "region must look like us-east-1 (got ${region})"

e2e_need_cmd terraform
e2e_terraform_init
e2e_tf validate -no-color

if [[ "$dry_run" -eq 1 ]]; then
  e2e_print_up_plan "$region"
  exit 0
fi

e2e_need_cmd aws
e2e_need_cmd jq
e2e_have_creds || e2e_die "no AWS credentials in the environment. Export AWS_ACCESS_KEY_ID and AWS_SECRET_ACCESS_KEY."

account="$(e2e_account_id)"
prefix="$(e2e_name_prefix "$account" "$region")"
glue_prefix="$(e2e_glue_prefix "$account" "$region")"
e2e_assert_name_prefix "$prefix"
e2e_assert_glue_prefix "$glue_prefix"

if [[ "$do_plan" -eq 1 ]]; then
  e2e_tf plan -input=false -no-color -var "region=${region}"
  exit 0
fi

e2e_log "applying Terraform in ${region} for ${prefix}"
e2e_tf apply -input=false -auto-approve -no-color -var "region=${region}"

state_dir="$(e2e_state_dir)"
mkdir -p "$state_dir"
outputs_file="${state_dir}/outputs.json"
e2e_tf output -json >"${outputs_file}.tmp"
mv "${outputs_file}.tmp" "$outputs_file"

actual_prefix="$(jq -r '.name_prefix.value' "$outputs_file")"
[[ "$actual_prefix" == "$prefix" ]] || e2e_die "Terraform name_prefix ${actual_prefix} does not match ${prefix}"

bucket="$(jq -r '.bucket_name.value' "$outputs_file")"
staging="$(jq -r '.s3_staging_dir.value' "$outputs_file")"
data_dir="$(jq -r '.s3_data_dir.value' "$outputs_file")"
work_group="$(jq -r '.work_group.value' "$outputs_file")"
schema="$(jq -r '.analytics_database.value' "$outputs_file")"
scratch="$(jq -r '.scratch_database.value' "$outputs_file")"
tag="$(jq -r '.project_tag.value' "$outputs_file")"

env_file="${state_dir}/e2e.env"
cat >"${env_file}.tmp" <<EOF
# Generated by infra/up.sh. Safe to delete; the next up.sh rewrites it.
# Credentials stay in the environment. This file does not contain keys.
E2E_REGION=${region}
E2E_ACCOUNT_ID=${account}
E2E_NAME_PREFIX=${prefix}
E2E_GLUE_PREFIX=${glue_prefix}
E2E_BUCKET=${bucket}
E2E_WORK_GROUP=${work_group}
E2E_SCHEMA=${schema}
E2E_SCRATCH_SCHEMA=${scratch}
E2E_S3_STAGING_DIR=${staging}
E2E_S3_DATA_DIR=${data_dir}
E2E_PROJECT_TAG=${tag}
DBT_ALLOW_EXPERIMENTAL_ADAPTERS=true
DBT_SEND_ANONYMOUS_USAGE_STATS=false
EOF
mv "${env_file}.tmp" "$env_file"

profiles="${state_dir}/profiles.yml"
cat >"${profiles}.tmp" <<EOF
# Generated by infra/up.sh. Do not commit.
# Auth is the AWS default credential chain (AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY
# or a role). Keys are intentionally absent so dbt debug never prints them.
dbt_v2_athena_e2e:
  target: dev
  outputs:
    dev:
      type: athena
      region_name: ${region}
      s3_staging_dir: ${staging}
      s3_data_dir: ${data_dir}
      s3_data_naming: schema_table_unique
      schema: ${schema}
      # catalog is accepted as an alias of database.
      database: awsdatacatalog
      work_group: ${work_group}
      threads: 1
EOF
mv "${profiles}.tmp" "$profiles"

e2e_log "wrote ${env_file}"
e2e_log "wrote ${profiles}"
e2e_log "bucket ${bucket}"
e2e_log "workgroup ${work_group}"
e2e_log "schema ${schema}"
e2e_log "scratch schema ${scratch}"
